"""Safe integration with the official dnscrypt-proxy executable.

Raider DNS does not implement DNSCrypt cryptography itself. It generates a
restricted configuration and delegates protocol handling to the upstream project.
Packaged installations may include the official, hash-verified Windows engine; a
user-supplied executable remains supported as an override.
"""
from __future__ import annotations

import os
import json
import base64
import socket
import subprocess
import sys
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Any

try:
    import tomllib
except ImportError:  # Python versions prior to 3.11 are not supported for this feature.
    tomllib = None  # type: ignore[assignment]

from raider_dns.models import DNSProvider
from raider_dns.services.dns_probe import probe_udp
from raider_dns.storage import app_data_dir


MINISIGN_PUBLIC_KEY = "RWQf6LRCGA9i53mlYecO4IzT51TGPpvWucNSCh1CBM0QTaLn73Y7GFO3"
RESOLVER_LIST_URLS = (
    "https://raw.githubusercontent.com/DNSCrypt/dnscrypt-resolvers/master/v3/public-resolvers.md",
    "https://download.dnscrypt.info/resolvers-list/v3/public-resolvers.md",
    "https://cdn.jsdelivr.net/gh/DNSCrypt/dnscrypt-resolvers@master/v3/public-resolvers.md",
)


@dataclass(slots=True)
class EngineResult:
    success: bool
    message: str
    details: str = ""


def render_hardened_config(config_path: Path, cache_path: Path) -> str:
    """Build a DNSCrypt-only configuration using signed-list security filters."""
    urls = ",\n    ".join(repr(u) for u in RESOLVER_LIST_URLS)
    # Keep server_names empty: the upstream project documents that require_*
    # filters do not apply when resolvers are explicitly pinned. This allows the
    # signed catalog to select only DNSCrypt servers meeting the DNSSEC/no-log
    # requirements while its latency-aware load balancer chooses among them.
    return f'''# Generated by Raider DNS. Review before use; do not edit manually.
listen_addresses = ['127.0.0.1:53', '[::1]:53']
max_clients = 250
ipv4_servers = true
ipv6_servers = false
dnscrypt_servers = true
doh_servers = false
odoh_servers = false
server_names = []
require_dnssec = true
require_nolog = true
require_nofilter = false
disabled_server_names = []
force_tcp = false
timeout = 5000
keepalive = 30
lb_strategy = 'wp2'
lb_estimator = true
timeout_load_reduction = 0.65
ignore_system_dns = true
bootstrap_resolvers = ['9.9.9.9:53', '1.1.1.1:53']
cache = true
cache_size = 4096
cache_min_ttl = 60
cache_max_ttl = 86400
cache_neg_min_ttl = 60
cache_neg_max_ttl = 600
dnscrypt_ephemeral_keys = false
pqdnscrypt = true

[sources.public-resolvers]
urls = [
    {urls}
]
cache_file = {json.dumps(str(cache_path))}
minisign_key = {MINISIGN_PUBLIC_KEY!r}
refresh_delay = 73
prefix = ''
'''


class DNSCryptProxyController:
    """Generate, validate, start and stop a local official dnscrypt-proxy process."""
    def __init__(self, binary_path: Path | None = None, config_path: Path | None = None) -> None:
        self.process: subprocess.Popen[bytes] | None = None
        self.external_pid: int | None = None
        # Persisted paths let a later app session identify only the exact
        # dnscrypt-proxy process/config it previously launched, avoiding a broad
        # taskkill by image name that could terminate unrelated user instances.
        self.binary_path: Path | None = binary_path
        self.config_path: Path | None = config_path
        self.log_path = app_data_dir() / "dnscrypt-proxy.log"

    @staticmethod
    def discover_bundled_binary() -> Path | None:
        """Find the engine installed beside Raider DNS, without searching arbitrary paths.

        The installer places the official engine under ``engines/dnscrypt-proxy``
        beside the app executable. Source builds may use the same layout at the
        repository root. No arbitrary folders or PATH entries are searched.
        """
        candidates: list[Path] = []
        try:
            executable_dir = Path(sys.executable).resolve().parent
            candidates.append(executable_dir / "engines" / "dnscrypt-proxy" / "dnscrypt-proxy.exe")
        except (OSError, RuntimeError):
            pass
        try:
            project_root = Path(__file__).resolve().parents[2]
            candidates.extend((
                project_root / "engines" / "dnscrypt-proxy" / "dnscrypt-proxy.exe",
            ))
        except (OSError, RuntimeError, IndexError):
            pass
        seen: set[str] = set()
        for candidate in candidates:
            try:
                identity = str(candidate.resolve()).casefold()
                if identity in seen:
                    continue
                seen.add(identity)
                if candidate.is_file():
                    return candidate.resolve()
            except (OSError, RuntimeError):
                continue
        return None

    @staticmethod
    def default_config_path() -> Path:
        return app_data_dir() / "dnscrypt-proxy" / "dnscrypt-proxy.generated.toml"

    @staticmethod
    def generate_config(config_path: Path | None = None) -> Path:
        path = config_path or DNSCryptProxyController.default_config_path()
        cache_path = path.parent / "public-resolvers.md"
        path.parent.mkdir(parents=True, exist_ok=True)
        text = render_hardened_config(path, cache_path)
        # Keep config private to the current user where the OS honors permissions.
        path.write_text(text, encoding="utf-8")
        try:
            os.chmod(path, 0o600)
        except OSError:
            pass
        return path

    @staticmethod
    def validate_config(path: Path) -> tuple[bool, str]:
        if tomllib is None:
            return False, "DNSCrypt config validation requires Python 3.11 or later."
        try:
            data = tomllib.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            return False, f"Invalid DNSCrypt TOML configuration: {exc}"
        if not isinstance(data, dict):
            return False, "DNSCrypt configuration root must be a TOML table."
        if data.get("listen_addresses") != ["127.0.0.1:53", "[::1]:53"]:
            return False, "DNSCrypt proxy must listen only on the IPv4 and IPv6 loopback addresses 127.0.0.1:53 and [::1]:53."
        if data.get("dnscrypt_servers") is not True or data.get("doh_servers") is not False or data.get("odoh_servers") is not False:
            return False, "Configuration must use DNSCrypt only; DoH/ODoH fallback is disabled."
        if data.get("ignore_system_dns") is not True or data.get("require_dnssec") is not True:
            return False, "Configuration must ignore system DNS for bootstrap and require DNSSEC-capable resolvers."
        cache_size = data.get("cache_size")
        if data.get("cache") is not True or not isinstance(cache_size, int) or isinstance(cache_size, bool) or cache_size < 256:
            return False, "Configuration must enable a reasonable local DNS cache."
        sources = data.get("sources", {})
        source = sources.get("public-resolvers", {}) if isinstance(sources, dict) else {}
        if not isinstance(source, dict):
            return False, "The official public resolver source must be a TOML table."
        approved_urls = set(RESOLVER_LIST_URLS)
        urls = source.get("urls", [])
        if source.get("minisign_key") != MINISIGN_PUBLIC_KEY or not isinstance(urls, list) or not urls or any(url not in approved_urls for url in urls):
            return False, "The official signed resolver list, approved HTTPS source URLs, and validation key are required."
        names = data.get("server_names", [])
        if not isinstance(names, list) or names:
            return False, "server_names must be empty (an empty list) so the signed catalog's DNSSEC/no-log resolver filters are enforced."
        if data.get("require_nolog") is not True or data.get("lb_strategy") != "wp2" or data.get("lb_estimator") is not True:
            return False, "Config must require no-log resolvers and use latency-aware load balancing."
        if data.get("pqdnscrypt") is not True:
            return False, "Post-quantum DNSCrypt should be enabled when the resolver supports it."
        timeout_ms = data.get("timeout")
        if not isinstance(timeout_ms, int) or isinstance(timeout_ms, bool) or not 1000 <= timeout_ms <= 10000:
            return False, "The DNSCrypt timeout is outside the supported safe range."
        if data.get("fallback_resolver") or data.get("fallback_resolvers"):
            return False, "Plain DNS fallback resolvers are not allowed in the DNSCrypt configuration."
        if data.get("bootstrap_resolvers") != ["9.9.9.9:53", "1.1.1.1:53"]:
            return False, "Bootstrap DNS must use the built-in pinned IP addresses rather than inherited system DNS."
        if data.get("query_log") or data.get("nx_log"):
            return False, "Query logging is not enabled by Raider DNS's privacy-focused configuration."
        return True, "DNSCrypt config passes local structural checks. The official executable must still validate it."

    @staticmethod
    def _ps_quote(value: str) -> str:
        return "'" + value.replace("'", "''") + "'"

    def _find_matching_process_id(self, binary: Path | None = None, config: Path | None = None) -> int | None:
        """Find a process only when both executable path and config path match."""
        if os.name != "nt":
            return None
        binary = binary or self.binary_path
        config = config or self.config_path
        if binary is None or config is None:
            return None
        script = (
            f"$expectedExe = {self._ps_quote(str(binary.resolve()))}; "
            f"$expectedConfig = {self._ps_quote(str(config.resolve()))}; "
            "$p = Get-CimInstance Win32_Process | Where-Object { $_.ExecutablePath -and "
            "$_.ExecutablePath -ieq $expectedExe -and $_.CommandLine -and "
            "$_.CommandLine.IndexOf($expectedConfig, [StringComparison]::OrdinalIgnoreCase) -ge 0 } | "
            "Select-Object -First 1; if ($p) { [Console]::Out.Write([string]$p.ProcessId) }"
        )
        encoded = base64.b64encode(script.encode("utf-16le")).decode("ascii")
        try:
            result = subprocess.run(["powershell.exe", "-NoLogo", "-NoProfile", "-NonInteractive", "-EncodedCommand", encoded],
                capture_output=True, text=True, timeout=5, check=False,
                creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
            raw = result.stdout.strip()
            return int(raw) if result.returncode == 0 and raw.isdigit() else None
        except (OSError, subprocess.SubprocessError, ValueError):
            return None

    @staticmethod
    def _loopback_dns_port_available() -> bool:
        # Verify UDP and TCP on both loopback address families. DNSCrypt must
        # accept IPv6-local requests too, otherwise a Windows IPv6 DNS path
        # could bypass the local encrypted proxy.
        endpoints = (
            (socket.AF_INET, ("127.0.0.1", 53)),
            (socket.AF_INET6, ("::1", 53)),
        )
        for family, address in endpoints:
            for sock_type in (socket.SOCK_DGRAM, socket.SOCK_STREAM):
                try:
                    with socket.socket(family, sock_type) as sock:
                        if family == socket.AF_INET6 and hasattr(socket, "IPV6_V6ONLY"):
                            sock.setsockopt(socket.IPPROTO_IPV6, socket.IPV6_V6ONLY, 1)
                        sock.bind(address)
                except OSError:
                    return False
        return True

    @staticmethod
    def validate_executable(binary: Path, config: Path, timeout: float = 10.0) -> EngineResult:
        if not binary.is_file():
            return EngineResult(False, "dnscrypt-proxy executable not found", str(binary))
        if not config.is_file():
            return EngineResult(False, "DNSCrypt configuration not found", str(config))
        valid, message = DNSCryptProxyController.validate_config(config)
        if not valid:
            return EngineResult(False, "DNSCrypt configuration rejected", message)
        try:
            result = subprocess.run(
                [str(binary), "-config", str(config), "-check"], capture_output=True,
                text=True, timeout=timeout, check=False,
                creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
            )
        except (OSError, subprocess.SubprocessError) as exc:
            return EngineResult(False, "Could not validate dnscrypt-proxy", str(exc))
        if result.returncode != 0:
            return EngineResult(False, "dnscrypt-proxy rejected the configuration", (result.stderr or result.stdout).strip())
        return EngineResult(True, "DNSCrypt configuration validated", (result.stdout or message).strip())

    def start(self, binary: Path, config: Path, timeout: float = 6.0) -> EngineResult:
        if self.process is not None and self.process.poll() is None:
            return EngineResult(True, "DNSCrypt proxy is already running.")
        if os.name != "nt":
            return EngineResult(False, "Windows-only operation", "This controller currently starts the Windows DNSCrypt proxy executable only.")
        self.binary_path = binary.resolve(); self.config_path = config.resolve()
        validation = self.validate_executable(self.binary_path, self.config_path)
        if not validation.success:
            return validation
        # If an earlier Raider DNS session left the proxy running to keep Windows
        # loopback DNS available, attach only to the exact executable+config pair.
        existing_pid = self._find_matching_process_id(self.binary_path, self.config_path)
        if existing_pid is not None:
            local = DNSProvider("local-dnscrypt", "Local DNSCrypt proxy", "Loopback test", "127.0.0.1", "", "Local")
            probe = probe_udp(local, timeout=0.75, domain="example.com")
            if probe.success:
                self.external_pid = existing_pid
                return EngineResult(True, "Previously started DNSCrypt proxy detected and verified", f"Verified the configured process (PID {existing_pid}) and local DNS response ({probe.latency_ms} ms).")
            return EngineResult(False, "Matching DNSCrypt process is running but not answering", "Windows DNS was not changed. Check the existing process log and listener.")
        if not self._loopback_dns_port_available():
            return EngineResult(False, "Local DNS loopback listener is unavailable", "UDP/TCP port 53 must be bindable on both 127.0.0.1 and ::1. It may be occupied, or IPv6 loopback may be unavailable. Raider DNS will not overwrite or terminate an unrelated process.")
        self.external_pid = None
        self.log_path.parent.mkdir(parents=True, exist_ok=True)
        try:
            # Keep the parent-side log handle scoped. Popen duplicates/inherits the
            # child standard handle as required; the parent must not leak a file
            # descriptor if process creation fails.
            with self.log_path.open("ab") as log_handle:
                self.process = subprocess.Popen(
                    [str(binary), "-config", str(config)], cwd=str(binary.parent),
                    stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=log_handle,
                    creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0), close_fds=True,
                )
            self.binary_path = binary
            self.config_path = config
        except OSError as exc:
            self.process = None
            return EngineResult(False, "Could not start DNSCrypt proxy", str(exc))
        local = DNSProvider("local-dnscrypt", "Local DNSCrypt proxy", "Loopback test", "127.0.0.1", "", "Local")
        deadline = time.monotonic() + max(0.5, timeout)
        while time.monotonic() < deadline:
            if self.process.poll() is not None:
                tail = self.log_path.read_text(encoding="utf-8", errors="replace")[-1500:] if self.log_path.exists() else ""
                return EngineResult(False, "DNSCrypt proxy exited during startup", tail)
            probe = probe_udp(local, timeout=0.35, domain="example.com")
            if probe.success:
                return EngineResult(True, "DNSCrypt proxy is running and answered a local DNS query.", f"Local query latency: {probe.latency_ms} ms")
            time.sleep(0.2)
        # A process being alive does not prove the resolver is ready. Stop rather
        # than applying loopback DNS to Windows when readiness cannot be proven.
        self.stop()
        return EngineResult(False, "DNSCrypt proxy did not answer a DNS query", "Windows DNS was not changed. Check port 53, the proxy log, and outbound connectivity.")

    def stop(self, timeout: float = 3.0) -> EngineResult:
        process = self.process
        if process is not None and process.poll() is None:
            try:
                process.terminate()
                process.wait(timeout=timeout)
            except subprocess.TimeoutExpired:
                try:
                    process.kill()
                    process.wait(timeout=timeout)
                except subprocess.TimeoutExpired:
                    # Keep the process reference so later recovery can inspect it;
                    # never report a successful stop while the listener may remain.
                    return EngineResult(
                        False,
                        "DNSCrypt proxy did not exit after termination",
                        "The process reference was retained. Verify that all adapters have been restored away from loopback DNS before retrying cleanup.",
                    )
                except OSError as exc:
                    return EngineResult(False, "Could not force-stop DNSCrypt proxy", str(exc))
            except OSError as exc:
                return EngineResult(False, "Could not stop DNSCrypt proxy", str(exc))
            if process.poll() is None:
                return EngineResult(
                    False,
                    "DNSCrypt proxy shutdown could not be confirmed",
                    "The process reference was retained; verify adapter DNS dependencies before retrying.",
                )
            self.process = None
            self.external_pid = None
            return EngineResult(True, "DNSCrypt proxy stopped.")
        self.process = None
        # A matching child can outlive the UI so that DNS set to 127.0.0.1 keeps
        # working while the window is closed. Re-identify it before termination.
        pid = self._find_matching_process_id()
        if pid is None:
            self.external_pid = None
            return EngineResult(True, "No matching Raider DNS DNSCrypt process is running.")
        try:
            result = subprocess.run(["taskkill.exe", "/PID", str(pid), "/T"], capture_output=True,
                text=True, timeout=timeout, check=False, creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
            if result.returncode != 0:
                # The PID is still verified against executable + config; force is
                # used only for that exact process tree, never by image name.
                result = subprocess.run(["taskkill.exe", "/PID", str(pid), "/T", "/F"], capture_output=True,
                    text=True, timeout=timeout, check=False, creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
            still_running = self._find_matching_process_id()
            if still_running is not None:
                return EngineResult(False, "DNSCrypt proxy could not be stopped", (result.stderr or result.stdout).strip())
            self.external_pid = None
            return EngineResult(True, f"DNSCrypt proxy stopped (PID {pid}).")
        except (OSError, subprocess.SubprocessError) as exc:
            return EngineResult(False, "Could not stop DNSCrypt proxy", str(exc))
